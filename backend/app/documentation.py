"""Generate structural documentation and explicit Python complexity estimates."""
from __future__ import annotations

import ast


class Decisions(ast.NodeVisitor):
    def __init__(self):
        self.count = 0

    def visit_FunctionDef(self, node):
        # Nested functions have their own metrics.
        return

    visit_AsyncFunctionDef = visit_FunctionDef

    def visit_ClassDef(self, node):
        return

    def generic_visit(self, node):
        if isinstance(node, (ast.If, ast.For, ast.AsyncFor, ast.While, ast.ExceptHandler, ast.IfExp)):
            self.count += 1
        elif isinstance(node, ast.BoolOp):
            self.count += len(node.values) - 1
        elif isinstance(node, ast.comprehension):
            self.count += 1 + len(node.ifs)
        elif isinstance(node, ast.Match):
            self.count += max(0, len(node.cases) - 1)
            self.count += sum(case.guard is not None for case in node.cases)
        super().generic_visit(node)


def python_metrics(text: str) -> list[dict]:
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return []
    metrics = []
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        decisions = Decisions()
        for statement in node.body:
            decisions.visit(statement)
        value = 1 + decisions.count
        args = [arg.arg for arg in node.args.posonlyargs + node.args.args]
        if node.args.vararg:
            args.append("*" + node.args.vararg.arg)
        args += [arg.arg + " (keyword-only)" for arg in node.args.kwonlyargs]
        if node.args.kwarg:
            args.append("**" + node.args.kwarg.arg)
        metrics.append({
            "name": node.name, "line": node.lineno,
            "end_line": node.end_lineno, "parameters": args,
            "cyclomatic_estimate": value,
            "review_priority": "high" if value >= 11 else "medium" if value >= 6 else "low",
        })
    return sorted(metrics, key=lambda m: m["line"])


def generate_documentation(project: str, files, impact: dict) -> str:
    def clean(value):
        return str(value).replace("\n", " ").replace("\r", " ").replace("`", "'").replace("<", "&lt;").replace(">", "&gt;")
    lines = [
        "# " + clean(project) + " — structural documentation",
        "",
        "Generated by static analysis. No uploaded code was executed or sent to an AI provider.",
        "This document describes detected structure, not inferred business purpose or proven runtime behavior.",
        "",
        "## Analysis boundaries",
        "",
        "Python functions use an estimated cyclomatic complexity: 1 plus if/loop/except/conditional-expression decisions, boolean operators, comprehension decisions, and match alternatives/guards. Nested functions are counted separately. Thresholds: 1–5 low, 6–10 medium, 11+ high review priority.",
        "Other language symbols and imports are heuristic; formal complexity is unavailable for them.",
        "Import reachability identifies review candidates, not guaranteed failures. Dynamic imports, runtime paths, decorators, external services, and data flows are not resolved.",
        "Literal default values and docstrings are omitted to avoid copying sensitive source content into documentation.",
        "",
        "## Inventory",
    ]
    for file in sorted(files, key=lambda f: f.path):
        lines += ["", "### " + clean(file.path), "",
                  f"Language: {file.language}. Lines: {file.lines}. Rule-based health: {file.score}/100.",
                  "", "Detected imports: " + (", ".join(clean(x) for x in file.imports) or "None detected."),
                  "", "#### Symbols"]
        lines += [f"- {clean(s.kind)} {clean(s.name)} — line {s.line}" for s in file.symbols] or ["- None detected."]
        lines += ["", "#### Python functions and complexity"]
        lines += [f"- {clean(m['name'])}({', '.join(clean(p) for p in m['parameters'])}) — lines {m['line']}–{m['end_line']}; complexity estimate {m['cyclomatic_estimate']}; review priority {m['review_priority']}." for m in file.complexity] or ["- Unavailable or no Python functions detected."]
        lines += ["", "#### Findings"]
        lines += [f"- [{f.severity}] {clean(f.rule)}: {clean(f.message)}" + (f" (line {f.line})" if f.line else "") for f in file.findings] or ["- No configured rule matched; this does not establish safety."]
        module = next((m for m in impact.get("modules", []) if m["changed_file"] == file.path), None)
        if module:
            lines += ["", "#### Potential change impact", f"{module['affected_count']} dependent files detected."]
            lines += ["- " + " → ".join(clean(p) for p in item["path"]) + "; evidence: " + ", ".join(f"{clean(e['source'])}:{e['line']} imports {clean(e['import'])}" for e in item["evidence"]) for item in module["affected"]]
    lines += ["", "## Unresolved imports", ""]
    lines += [f"- {clean(e['source'])}:{e['line']} — {clean(e['import'])}: {e['reason']}" for e in impact.get("unresolved_imports", [])] or ["None detected in the supported static import scan."]
    lines += ["", "## Human documentation still needed", "",
              "- Business purpose, ownership, operating requirements, and deployment instructions.",
              "- Runtime API contracts and data schemas, validated against real behavior.",
              "- Characterization tests before making changes to high-impact modules."]
    return "\n".join(lines) + "\n"
